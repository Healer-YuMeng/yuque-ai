def build_friend_v5_system_prompt_with_scene_intro(
    *,
    scene_intro: str = "",
    decision_intro: str = "",
    user_intro: str = "",
    visitor_type: str = "",
) -> str:
    base = build_friend_v5_system_prompt()
    common = (scene_intro or "").strip()
    decision = (decision_intro or "").strip()
    user = (user_intro or "").strip()
    vt = (visitor_type or "").strip()
    if not common and not decision and not user:
        return base
    role_hint = _visitor_role_prompt_hint(vt)
    selected_intro = ""
    if vt == "institution_decision_maker" and decision:
        selected_intro = decision
    elif vt in {"teacher", "parent", "student"} and user:
        selected_intro = user
    elif common:
        selected_intro = common
    elif decision:
        selected_intro = decision
    else:
        selected_intro = user
    common_block = f"【通用口径】\n{common}\n" if common else ""
    decision_block = f"【决策者口径】\n{decision}\n" if decision else ""
    user_block = f"【使用者口径】\n{user}\n" if user else ""
    return (
        f"{base}\n\n"
        "【后台维护的当前场景产品介绍】\n"
        "下面这些内容是管理员在后台维护的当前场景产品介绍，优先按这段口径理解当前产品事实；"
        "如果它和默认产品介绍并存，以这里为准，但仍需保持自然表达，不要整段背诵。\n"
        f"当前识别到的访客身份：{role_hint}\n"
        f"{common_block}"
        f"{decision_block}"
        f"{user_block}"
        f"【本轮优先采用口径】\n{selected_intro}"
    )


def _visitor_role_prompt_hint(visitor_type: str) -> str:
    vt = (visitor_type or "").strip()
    if vt == "institution_decision_maker":
        return "决策者（校长/负责人）"
    if vt == "teacher":
        return "使用者（老师）"
    if vt == "parent":
        return "使用者（家长）"
    if vt == "student":
        return "使用者（学生）"
    return "暂未明确"


